/**
 * Regenerate the per-saver structure baselines used by shadercheck (#156).
 *
 * Runs the shadercheck harness, reads the densities it measured, and rewrites
 * structure-baselines.js.
 *
 * Generating them from the same harness that checks them is the point. Edge
 * density is resolution-dependent, so baselines measured in any other context
 * bake in that context's canvas size -- taking them at 600x300 while the
 * harness runs full-viewport produced 13 false positives on healthy savers.
 *
 * Usage: npm run baselines
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
// The harness exits non-zero when any saver fails, which includes a saver whose
// structure has drifted below its recorded baseline -- and that is exactly the
// state we are here to correct. So read its output regardless of exit code, and
// only bail if no densities came back at all.
let out
try {
  out = execFileSync('node', [path.join(root, 'scripts', 'shader-check.mjs')], {
    cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024
  })
} catch (err) {
  // execFileSync throws on non-zero exit but still captures stdout.
  out = (err.stdout || '') + (err.stderr || '')
}

const match = out.match(/SHADERCHECK_DENSITIES (\{.*\})/)
if (!match) {
  console.error('No densities in the harness output. Did shadercheck fail to run?')
  process.exit(1)
}

const densities = JSON.parse(match[1])
const names = Object.keys(densities).sort((a, b) => densities[b] - densities[a])

const header = [
  '// SPDX-License-Identifier: Apache-2.0',
  '// SPDX-FileCopyrightText: 2025-2026 Schuberg Philis / Lab271',
  '/**',
  ' * Per-saver structure baselines for shadercheck (issue #156).',
  ' *',
  ' * GENERATED by scripts/update-structure-baselines.mjs -- do not hand-edit.',
  ' *',
  ' * Edge density is the fraction of horizontally adjacent pixels differing by',
  ' * more than 6% luminance: a proxy for "does this frame have visible',
  ' * structure". It is what would have caught the physarum failure, where the',
  ' * simulation was correct but the display pass rendered a flat gradient,',
  ' * scoring exactly 0.000 while every existing pixel check passed.',
  ' *',
  ' * These cannot be replaced by one global threshold, and the spread is why:',
  ' * some savers legitimately sit near 0.002 while others reach 0.67. Any floor',
  ' * above the lowest healthy saver false-positives on it, and any floor below',
  ' * catches nothing. So the check is a large relative DROP from a saver\'s own',
  ' * baseline.',
  ' *',
  ' * Values are the minimum across the harness seeds, measured on SwiftShader.',
  ' *',
  ' * A baseline of 0 means the saver had nothing on screen after the harness\'s',
  ' * five frames -- true of simulations that need seconds to develop (wave tank\'s',
  ' * first drop lands at 0.2s; falling sand has ~40 grains on a 240x135 grid by',
  ' * then). The check skips a zero baseline, so those savers are NOT protected by',
  ' * it. Verify them by sampling over time instead, as their commits did.',
  ' * Regenerate with `npm run baselines` and review the diff: a baseline that',
  ' * drops sharply is either an intended redesign or the bug this file exists',
  ' * to catch.',
  ' */',
  'export const STRUCTURE_BASELINES = {'
].join('\n')

const body = names.map((n) => `  ${JSON.stringify(n)}: ${Number(densities[n].toFixed(4))},`).join('\n')
const file = path.join(root, 'src', 'renderer', 'screensavers', 'structure-baselines.js')
writeFileSync(file, `${header}\n${body}\n}\n`)
console.log(`Wrote ${names.length} baselines to ${path.relative(root, file)}`)
